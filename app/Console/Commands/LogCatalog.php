<?php

namespace App\Console\Commands;

use App\Logging\Enums\ActorType;
use App\Logging\Enums\Courier;
use App\Logging\Enums\Ctx;
use App\Logging\Enums\LogDomain;
use App\Logging\Enums\Reason;
use App\Logging\Enums\Retention;
use App\Logging\Enums\Severity;
use Illuminate\Console\Command;

class LogCatalog extends Command
{
    protected $signature = 'log:catalog {--check : Fail if docs/logging/catalog.md is out of date instead of writing it}';

    protected $description = 'Generate docs/logging/catalog.md from the event enums';

    public function handle(): int
    {
        $path = base_path('docs/logging/catalog.md');
        $markdown = self::markdown();

        if ($this->option('check')) {
            if (! is_file($path) || file_get_contents($path) !== $markdown) {
                $this->error('docs/logging/catalog.md is out of date. Run: php artisan log:catalog');

                return self::FAILURE;
            }

            return self::SUCCESS;
        }

        @mkdir(dirname($path), 0755, true);
        file_put_contents($path, $markdown);
        $this->info('Wrote docs/logging/catalog.md');

        return self::SUCCESS;
    }

    public static function markdown(): string
    {
        $out = "# Log catalog\n\n> Generated by `php artisan log:catalog`. Never edit by hand.\n\n";

        $out .= "## Events\n\n";

        foreach (LogDomain::cases() as $domain) {
            $channel = $domain->channel() ?? 'default';
            $out .= "### {$domain->value} {$domain->name}\n\n{$domain->description()}. Default channel: `{$channel}`.\n\n";

            $cases = $domain->eventEnum()::cases();

            if ($cases === []) {
                $out .= "_No events yet._\n\n";

                continue;
            }

            $out .= "| ID | Constant | Severity | Keep | Description | Required | Optional |\n|---|---|---|---|---|---|---|\n";

            foreach ($cases as $event) {
                $spec = $event->spec();
                $out .= sprintf(
                    "| %d | `%s` | %s | %s | %s | %s | %s |\n",
                    $event->id(),
                    $event->name,
                    $spec->severity->name,
                    $spec->keep->name,
                    str_replace('|', '\\|', $spec->description).($spec->channel ? " (channel `{$spec->channel}`)" : ''),
                    self::keys($spec->required),
                    self::keys($spec->optional),
                );
            }

            $out .= "\n";
        }

        $out .= "## Context keys\n\n| Key | Name | Type | Meaning |\n|---|---|---|---|\n";
        foreach (Ctx::cases() as $ctx) {
            $out .= "| `{$ctx->value}` | {$ctx->name} | {$ctx->type()->value} | {$ctx->description()} |\n";
        }

        $out .= "\n## Reasons (`rsn`)\n\n| ID | Name | Meaning |\n|---|---|---|\n";
        foreach (Reason::cases() as $reason) {
            $out .= "| {$reason->value} | {$reason->name} | {$reason->description()} |\n";
        }

        $out .= "\n## Couriers (`crr`)\n\n| ID | Name | Meaning |\n|---|---|---|\n";
        foreach (Courier::cases() as $courier) {
            $out .= "| {$courier->value} | {$courier->name} | {$courier->description()} |\n";
        }

        $out .= "\n## Retention (`k`)\n\n| ID | Name | Meaning |\n|---|---|---|\n";
        foreach (Retention::cases() as $keep) {
            $out .= "| {$keep->value} | {$keep->name} | {$keep->description()} |\n";
        }

        $out .= "\n## Severity (`l`)\n\n| ID | Name |\n|---|---|\n";
        foreach (Severity::cases() as $severity) {
            $out .= "| {$severity->value} | {$severity->name} |\n";
        }

        $out .= "\n## Actor types (`at`)\n\n| ID | Name | Meaning |\n|---|---|---|\n";
        foreach (ActorType::cases() as $actor) {
            $out .= "| {$actor->value} | {$actor->name} | {$actor->description()} |\n";
        }

        return $out;
    }

    /** @param list<Ctx> $keys */
    private static function keys(array $keys): string
    {
        return $keys === [] ? '—' : implode(', ', array_map(fn (Ctx $c) => "`{$c->value}`", $keys));
    }
}
